#!/usr/bin/env bash
# Rebuilds vendor/ from node_modules (run `npm ci` first). Self-hosted assets only.
set -euo pipefail
cd "$(dirname "$0")/.."
NM=node_modules
CM=$NM/codemirror
V=vendor
mkdir -p $V/codemirror $V/fonts
cp $CM/lib/codemirror.js $CM/lib/codemirror.css $V/codemirror/
cp $CM/mode/javascript/javascript.js $V/codemirror/mode-javascript.js
cp $CM/mode/python/python.js $V/codemirror/mode-python.js
cp $CM/addon/edit/closebrackets.js $V/codemirror/closebrackets.js
cp $CM/addon/edit/matchbrackets.js $V/codemirror/matchbrackets.js
cp $CM/addon/comment/comment.js $V/codemirror/comment.js
cp $CM/LICENSE $V/codemirror/LICENSE
rm -f $V/fonts/*.woff2
font() { # package weight...
  local pkg=$1; shift
  for w in "$@"; do cp "$NM/@fontsource/$pkg/files/$pkg-latin-$w-normal.woff2" "$V/fonts/"; done
}
font bricolage-grotesque 600 700 800
font instrument-sans 400 500 600
font jetbrains-mono 400 500
{
  echo "/* Generated by scripts/vendor.sh. Latin subset, SIL OFL 1.1. */"
  face() { printf "@font-face{font-family:'%s';font-style:normal;font-weight:%s;font-display:swap;src:url('%s-latin-%s-normal.woff2') format('woff2');}\n" "$2" "$3" "$1" "$3"; }
  for w in 600 700 800; do face bricolage-grotesque "Bricolage Grotesque" $w; done
  for w in 400 500 600; do face instrument-sans "Instrument Sans" $w; done
  for w in 400 500; do face jetbrains-mono "JetBrains Mono" $w; done
} > $V/fonts/fonts.css
echo "vendor/ rebuilt: $(du -sh $V | cut -f1)"
